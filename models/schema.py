from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(..., description="List of messages exchanged with the agent.")
    user_question: str = Field(..., description="The original question asked by the user.")
    curated_ques: str = Field(..., description="Curated user question.")
    prompot_query_context: str = Field(..., description="A detailed Prompt with Postgres SQL query context for the agent to generate SQL query.")
    is_safe: Literal["Yes", "No"] = Field(..., description="Indicates whether the generated SQL query is safe to execute.")
    comments: str = Field(..., description="Additional comments or feedback regarding the safety of the SQL query.")
    generated_sql_query: str = Field(..., description="The SQL query generated by the agent based on the provided context and user question.")
    sql_query_execution_result: str = Field(..., description="The result of executing the generated SQL query.")
    final_answer: str = Field(..., description="The final answer provided by the agent after processing the SQL query execution result.")

class JudgeSchema(BaseModel):
    answer : Literal["Yes","No"] = Field(..., description="Indicates whether the generated SQL query is safe to execute or not")
    comments : str = Field(..., description="Additional comments or feedback from the judge regarding the SQL query")
